#!/usr/bin/env python3
"""Capture a finite, paired HotSpot ring comparison in a bounded Linux cgroup."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import time

from verify_oracle import CONFIGURATIONS, expected

HERE = Path(__file__).resolve().parent
FIXTURES = HERE.parents[2] / "ristretto_vm/tests/fixtures/canonical"
CLASSES = ("CanonicalRingWorkload", "CanonicalRingWorkload$Node")
COLLECTORS = {"G1": "-XX:+UseG1GC", "ZGC": "-XX:+UseZGC"}


def resource_limits():
    root = Path("/sys/fs/cgroup")
    group = next(line[3:] for line in Path("/proc/self/cgroup").read_text().splitlines()
                 if line.startswith("0::"))
    directory = root / group.lstrip("/")
    memory = []
    cpu = []
    while directory != root:
        limit = directory / "memory.max"
        if limit.exists() and (value := limit.read_text().strip()) != "max":
            memory.append(int(value))
        quota = directory / "cpu.max"
        if quota.exists():
            value, period = quota.read_text().split()
            if value != "max":
                cpu.append(int(value) / int(period))
        directory = directory.parent
    if not memory or not cpu:
        raise SystemExit("run inside a cgroup with finite memory.max and cpu.max (see README)")
    return dict(cgroup=group, memory_max_bytes=min(memory), cpu_quota=min(cpu),
                affinity=sorted(os.sched_getaffinity(0)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--workload", choices=CONFIGURATIONS, default="small")
    parser.add_argument("--steps", type=int, default=257)
    parser.add_argument("--warmup", type=int, default=10)
    parser.add_argument("--samples", type=int, default=8)
    parser.add_argument("--forks", type=int, default=3)
    args = parser.parse_args()
    if not (0 <= args.steps <= 100000 and 0 <= args.warmup <= 128
            and 1 <= args.samples <= 128 and 1 <= args.forks <= 32):
        parser.error("sample plan exceeds finite limits")
    if args.output.exists():
        parser.error("output already exists")
    env = os.environ.copy()
    for key in ("JAVA_TOOL_OPTIONS", "JDK_JAVA_OPTIONS", "_JAVA_OPTIONS", "JDK_JAVAC_OPTIONS"):
        env.pop(key, None)
    java = shutil.which("java")
    javac = shutil.which("javac")
    if not java or not javac:
        parser.error("put the HotSpot JDK launchers on PATH")
    os.sched_setaffinity(0, sorted(os.sched_getaffinity(0))[:2])
    limits = resource_limits()
    checksum = expected(args.workload, args.steps)
    flags = ["-Xms64m", "-Xmx64m", f"-XX:ActiveProcessorCount={len(limits['affinity'])}"]
    version = subprocess.check_output([java, "-version"], stderr=subprocess.STDOUT, text=True, env=env)
    hashes = {}
    captures = []
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([javac, "--release", "17", "-g", "-d", tmp,
                        FIXTURES / "CanonicalRingWorkload.java", HERE / "RingSamples.java"],
                       check=True, env=env)
        for name in CLASSES:
            path = FIXTURES / (name + ".class")
            if path.read_bytes() != (Path(tmp) / path.name).read_bytes():
                raise SystemExit(f"regenerated bytecode differs: {path.name}")
            hashes[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
        for fork in range(args.forks):
            for collector in (list(COLLECTORS) if fork % 2 == 0 else reversed(COLLECTORS)):
                if resource_limits() != limits:
                    raise SystemExit("resource limits changed during capture")
                vm_flags = [*flags, COLLECTORS[collector]]
                command = [java, *vm_flags, "-cp", tmp, "RingSamples", args.workload,
                           str(args.steps), str(checksum), str(args.warmup), str(args.samples)]
                start = time.monotonic_ns()
                output = subprocess.check_output(command, text=True, timeout=300, env=env)
                process_ns = time.monotonic_ns() - start
                beans = []
                samples = []
                for line in output.splitlines():
                    kind, *values = line.split("\t")
                    if kind == "collector":
                        beans.append(values[0])
                    elif kind == "sample":
                        result, elapsed = map(int, values)
                        if result != checksum or elapsed < 0:
                            raise ValueError(line)
                        samples.append(dict(checksum=result, elapsed_ns=elapsed))
                    else:
                        raise ValueError(line)
                prefix = "G1" if collector == "G1" else "Z"
                if not any(name.startswith(prefix) for name in beans) or len(samples) != args.samples:
                    raise SystemExit("collector or sample count mismatch")
                captures.append(dict(fork=fork, collector=collector, beans=beans, flags=vm_flags,
                                     process_ns=process_ns, samples=samples))
    with args.output.open("x") as stream:
        json.dump(dict(schema=1, jdk=version.strip(), java=str(Path(java).resolve()), limits=limits,
                       workload=args.workload, steps=args.steps, expected=checksum,
                       warmup=args.warmup, class_sha256=hashes, processes=captures),
                  stream, indent=2)
        stream.write("\n")


if __name__ == "__main__":
    main()
